CRARC="${1:-crarc}"

read_crarc() {
	if test -z "$NO_BUILTIN_CRARC"; then
		sed 's/[[:space:]]*#.*//' "$CRARC" | sed 's,\\,\\\\,g' | sed 's,",\\",g' | sed 's/	\+/	/g'
	else
		echo '#'
	fi
}

echo "/* Generated by $0 */"
echo "const char *builtin_config ="

read_crarc | while read -r line; do
	case "$line" in
	"")	: ignore ;;
	*)	printf '	"%s\\n"\n' "$line"
	esac
done

echo ";"
